// Generates the package's declarations for each interface version the kit
// builds plugins against: plugin-sdk's WIT, the one definition of Noura's
// plugin interface, under its current version, and the frozen copy of each
// earlier version that @noura/plugin-cli keeps building. A plugin built
// against an earlier version keeps its types.
//
// Each version gets a folder in `generated/`: the modules
// `noura:plugin/<interface>@<version>` that jco declares from its WIT, and an
// `index.d.ts` with the types of what a plugin exports, which
// `@noura/plugin-types/<version>` gives. `generated/versions.d.ts` declares
// the modules of every version.
//
// `--wit`, `--frozen` and `--out` replace the current WIT, the folder of
// frozen versions and the package's folder, for the kit's tests.
import { execFileSync } from 'node:child_process';
import {
	existsSync,
	readFileSync,
	readdirSync,
	rmSync,
	writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { values: options } = parseArgs({
	options: {
		wit: { type: 'string' },
		frozen: { type: 'string' },
		out: { type: 'string' },
	},
});
const wit = resolve(
	options.wit ?? join(here, '../../../../../crates/plugin-sdk/wit'),
);
const frozen = resolve(
	options.frozen ?? join(here, '../../plugin-cli/wit-frozen'),
);
const out = join(resolve(options.out ?? join(here, '..')), 'generated');

/** A version folder's name. */
const VERSION = /^[0-9]+\.[0-9]+\.[0-9]+$/;

/** The `noura:plugin` version the WIT in `folder` declares. */
function versionOf(folder) {
	const version = /^package noura:plugin@([0-9.]+);/m.exec(
		readFileSync(join(folder, 'plugin.wit'), 'utf8'),
	)?.[1];
	if (!version) {
		throw new Error(`${folder}/plugin.wit names no noura:plugin version.`);
	}
	return version;
}

/** The WIT folder of each version, by version: the frozen ones, then the current one. */
const versions = new Map();
if (existsSync(frozen)) {
	for (const name of readdirSync(frozen)) {
		if (VERSION.test(name)) {
			versions.set(name, join(frozen, name));
		}
	}
}
versions.set(versionOf(wit), wit);

/** The types of what a plugin built against `version` exports. */
function exportsOf(version) {
	return `// What a plugin built against noura:plugin@${version} exports. Generated
// by scripts/generate.mjs from the version's WIT.
//
// A plugin's \`src/plugin.ts\` exports an object for each interface it
// offers Noura, typed with the \`...Exports\` types below. Each function is
// optional: the build fills in one that returns nothing, so a plugin writes
// only the ones for the capabilities its manifest declares.

/// <reference path="./plugin.d.ts" />

import type * as View from 'noura:plugin/view@${version}';
import type * as ObjectTypes from 'noura:plugin/object-types@${version}';
import type * as Commands from 'noura:plugin/commands@${version}';
import type * as Inbox from 'noura:plugin/inbox@${version}';
import type * as Settings from 'noura:plugin/settings@${version}';
import type * as Tools from 'noura:plugin/tools@${version}';

/** Pages in the rail and their views. Needs the \`views\` capability. */
export type ViewExports = Partial<typeof View>;

/** Object types and their properties panels. Needs \`object-types\`. */
export type ObjectTypesExports = Partial<typeof ObjectTypes>;

/** Commands for the command palette and other plugins. Needs \`commands\`. */
export type CommandsExports = Partial<typeof Commands>;

/** Sections in the Inbox. Needs \`inbox-sections\`. */
export type InboxExports = Partial<typeof Inbox>;

/** A page in Settings. Needs \`settings\`. */
export type SettingsExports = Partial<typeof Settings>;

/** Tools for AI assistants. Needs \`tools\`. */
export type ToolsExports = Partial<typeof Tools>;
`;
}

rmSync(out, { recursive: true, force: true });
const jco = join(
	dirname(createRequire(import.meta.url).resolve('@bytecodealliance/jco')),
	'jco.js',
);
const sorted = [...versions.keys()].sort((a, b) =>
	a.localeCompare(b, 'en', { numeric: true }),
);
for (const version of sorted) {
	const folder = join(out, version);
	execFileSync(
		process.execPath,
		[
			jco,
			'guest-types',
			versions.get(version),
			'--world-name',
			'plugin',
			'--out-dir',
			folder,
			'--quiet',
		],
		{ stdio: 'inherit' },
	);
	writeFileSync(join(folder, 'index.d.ts'), exportsOf(version));
}
writeFileSync(
	join(out, 'versions.d.ts'),
	`// The modules of every noura:plugin version the kit builds. Generated by
// scripts/generate.mjs.
${sorted.map((version) => `/// <reference path="./${version}/plugin.d.ts" />`).join('\n')}
`,
);
