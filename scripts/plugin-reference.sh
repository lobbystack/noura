#!/usr/bin/env bash
# Writes the plugin interface reference, docs/plugins/reference/, from the
# doc comments in plugin-sdk's WIT with wit-bindgen's Markdown generator, so
# the reference never drifts from the interface. CI runs this and fails
# when the committed reference differs.
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
wit="$repo/crates/plugin-sdk/wit"
wanted="0.63.0"

if ! command -v wit-bindgen >/dev/null; then
  echo "wit-bindgen isn't installed. Run: cargo install wit-bindgen-cli --version $wanted --locked" >&2
  exit 1
fi
found="$(wit-bindgen --version | awk '{print $2}')"
if [ "$found" != "$wanted" ]; then
  echo "wit-bindgen $found is installed; the reference is generated with $wanted." >&2
  exit 1
fi

version="$(sed -n 's/^package noura:plugin@\(.*\);$/\1/p' "$wit/plugin.wit")"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
wit-bindgen markdown "$wit" --world plugin --out-dir "$work" >/dev/null

mkdir -p "$repo/docs/plugins/reference"
{
  echo "<!-- Generated by scripts/plugin-reference.sh from crates/plugin-sdk/wit. Edit the WIT, not this file. -->"
  echo
  cat "$work/plugin.md"
} >"$repo/docs/plugins/reference/noura-plugin-$version.md"
